-- ============================================================================
-- 8) Project the KV dump into the normalized tables (queryable mirror)
-- ============================================================================
-- Pure SQL derived from the kv_store rows above, so the mirror is always in
-- sync with the dump and the whole file stays idempotent/re-runnable.

-- coaches <- acct:<email>
insert into public.coaches as c (id, email, name, pass_salt, pass_hash, plan, workspace_id,
                                 trial_ends_at, sub_status, sub_ends_at, sub_started_at, created_at)
select v->>'id',
       lower(v->>'email'),
       coalesce(v->>'name', ''),
       coalesce(v #>> '{pass,salt}', ''),
       coalesce(v #>> '{pass,hash}', ''),
       coalesce(v->>'plan', 'trial'),
       nullif(v->>'workspaceId', ''),
       public.ms_to_ts(v->>'trialEndsAt'),
       coalesce(v->>'sub_status', 'trial'),
       public.ms_to_ts(v->>'sub_ends_at'),
       public.ms_to_ts(v->>'sub_started_at'),
       coalesce(public.ms_to_ts(v->>'createdAt'), now())
from (select value as v from public.kv_store where key like 'coach-os-saas:acct:%') s
where v->>'id' is not null and v->>'email' is not null
on conflict (id) do update set
  email = excluded.email, name = excluded.name,
  pass_salt = excluded.pass_salt, pass_hash = excluded.pass_hash,
  plan = excluded.plan, workspace_id = excluded.workspace_id,
  trial_ends_at = excluded.trial_ends_at, sub_status = excluded.sub_status,
  sub_ends_at = excluded.sub_ends_at, sub_started_at = excluded.sub_started_at;

-- admin_users <- acct:<email> where role='admin'
insert into public.admin_users as a (id, email, name, pass_salt, pass_hash, role, created_at)
select v->>'id',
       lower(v->>'email'),
       coalesce(v->>'name', ''),
       coalesce(v #>> '{pass,salt}', ''),
       coalesce(v #>> '{pass,hash}', ''),
       coalesce(v->>'role', 'admin'),
       coalesce(public.ms_to_ts(v->>'createdAt'), now())
from (select value as v from public.kv_store where key like 'coach-os-saas:acct:%') s
where v->>'id' is not null and v->>'email' is not null and v->>'role' = 'admin'
on conflict (id) do update set
  email = excluded.email, name = excluded.name,
  pass_salt = excluded.pass_salt, pass_hash = excluded.pass_hash, role = excluded.role;

-- workspaces <- ws:<id>  (owner "coach:<id>" -> owner_coach_id, only if it exists)
insert into public.workspaces as w (id, code, owner_coach_id, plan, status, created_at, claimed_at)
select v->>'id',
       v->>'code',
       case when v->>'owner' like 'coach:%'
             and exists (select 1 from public.coaches c
                         where c.id = substring(v->>'owner' from 7))
            then substring(v->>'owner' from 7) end,
       coalesce(v->>'plan', 'trial'),
       coalesce(v->>'status', 'trial'),
       coalesce(public.ms_to_ts(v->>'createdAt'), now()),
       public.ms_to_ts(v->>'claimedAt')
from (select value as v from public.kv_store where key like 'coach-os-saas:ws:%') s
where v->>'id' is not null and v->>'code' is not null
on conflict (id) do update set
  code = excluded.code, owner_coach_id = excluded.owner_coach_id,
  plan = excluded.plan, status = excluded.status,
  created_at = excluded.created_at, claimed_at = excluded.claimed_at;

-- sessions <- sess:<token>  (skip orphans whose coach no longer exists)
insert into public.sessions (token, coach_id, email, created_at, expires_at)
select substring(key from length('coach-os-saas:sess:') + 1),
       v->>'coachId',
       coalesce(v->>'email', ''),
       coalesce(public.ms_to_ts(v->>'createdAt'), now()),
       coalesce(public.ms_to_ts(v->>'expiresAt'), now() + interval '30 days')
from (select key, value as v from public.kv_store where key like 'coach-os-saas:sess:%') s
where v->>'coachId' is not null
  and exists (select 1 from public.coaches c where c.id = v->>'coachId')
on conflict (token) do update set
  email = excluded.email, created_at = excluded.created_at, expires_at = excluded.expires_at;

-- workspace_data <- ws-meta:<wid>
insert into public.workspace_data as d (workspace_id, rev, data, updated_at)
select substring(key from length('coach-os-saas:ws-meta:') + 1),
       coalesce((v->>'rev')::bigint, 0),
       coalesce(v->'data', '{}'::jsonb),
       coalesce(public.ms_to_ts(v->>'updatedAt'), now())
from (select key, value as v from public.kv_store where key like 'coach-os-saas:ws-meta:%') s
where exists (select 1 from public.workspaces w
              where w.id = substring(key from length('coach-os-saas:ws-meta:') + 1))
on conflict (workspace_id) do update set
  rev = excluded.rev, data = excluded.data, updated_at = excluded.updated_at;

-- coupons <- coupon:<CODE>
insert into public.coupons as cp (code, plan_id, duration_days, max_uses, used_count,
                                  is_active, expires_at, created_at)
select v->>'code',
       coalesce(v->>'planId', 'basic'),
       coalesce((v->>'durationDays')::int, 30),
       coalesce((v->>'maxUses')::int, 1),
       coalesce((v->>'usedCount')::int, 0),
       coalesce((v->>'isActive')::boolean, true),
       public.ms_to_ts(v->>'expiresAt'),
       coalesce(public.ms_to_ts(v->>'createdAt'), now())
from (select value as v from public.kv_store where key like 'coach-os-saas:coupon:%') s
where v->>'code' is not null
  and exists (select 1 from public.plans p where p.id = coalesce(v->>'planId', 'basic'))
on conflict (code) do update set
  plan_id = excluded.plan_id, duration_days = excluded.duration_days,
  max_uses = excluded.max_uses, used_count = excluded.used_count,
  is_active = excluded.is_active, expires_at = excluded.expires_at;

-- payments <- pay:<id>
insert into public.payments as pay (id, coach_id, plan_id, amount, currency, provider,
                                    tracking_code, status, coupon_code, starts_at, ends_at, created_at)
select v->>'id',
       v->>'coachId',
       coalesce(v->>'planId', 'trial'),
       coalesce((v->>'amount')::numeric, 0),
       coalesce(v->>'currency', 'IRT'),
       coalesce(v->>'provider', 'manual'),
       coalesce(v->>'tracking', ''),
       coalesce(v->>'status', 'pending'),
       -- The app never writes a `couponCode` field: coupon payments carry the
       -- code in `tracking` (see netlify/lib/billing.mjs redeem()). Reading
       -- only `couponCode` left this column permanently NULL, so the coupon
       -- code actually lived in tracking_code and coupon_code was dead weight.
       coalesce(nullif(v->>'couponCode', ''),
                case when coalesce(v->>'provider', '') = 'coupon'
                     then nullif(v->>'tracking', '') end),
       public.ms_to_ts(v->>'startsAt'),
       public.ms_to_ts(v->>'endsAt'),
       coalesce(public.ms_to_ts(v->>'createdAt'), now())
from (select value as v from public.kv_store where key like 'coach-os-saas:pay:%') s
where v->>'id' is not null
  and exists (select 1 from public.coaches c where c.id = v->>'coachId')
on conflict (id) do update set
  plan_id = excluded.plan_id, amount = excluded.amount, currency = excluded.currency,
  provider = excluded.provider, tracking_code = excluded.tracking_code,
  status = excluded.status, coupon_code = excluded.coupon_code,
  starts_at = excluded.starts_at, ends_at = excluded.ends_at;

commit;

