-- ONE file = everything the backend needs: tables, indexes, the full dump of
-- the project KV store (admin + coach accounts, sessions, workspaces, coupons,
-- payments, shop orders, workspace payloads) and SQL that projects that dump
-- into normalized, queryable tables.
--
-- Usage:
--   createdb coach_os
--   psql -d coach_os -f db/schema.sql
--   # or directly with a connection URL:
--   psql "postgres://user:pass@host:5432/coach_os" -f db/schema.sql
--
-- Then point the app at it (server.mjs, Netlify, Docker â€” everywhere):
--   DATABASE_URL=postgres://user:pass@host:5432/coach_os node server.mjs
--
-- Notes:
--   * The DDL section is idempotent: safe to run twice (create if not exists +
--     create or replace + upserts on the static plans seed).
--   * âڑ ï¸ڈ THE DATA SECTION IS NOT A NO-OP ON A LIVE DATABASE. It is a snapshot
--     dump (see the source/date in the KV-DATA header) and every row is an
--     unconditional `insert â€¦ on conflict do update`. Re-running this file
--     against a database that is already serving traffic REVERTS every account
--     (including pass.salt/pass.hash, plan and sub_ends_at), every session and
--     every workspace payload to that snapshot. Run it once on a fresh
--     database; to just create the empty schema, delete the section between
--     the KV-DATA-BEGIN / KV-DATA-END markers first.
--   * No Supabase, no PostgREST, no RLS: the app connects directly with its
--     own Postgres role. Restrict that role with plain GRANTs if needed.
--   * The KV data section between the KV-DATA markers is generated by
--     scripts/export-kv-to-sql.mjs (npm run db:dump). Do not edit by hand.
-- ============================================================================

begin;

-- ---------------------------------------------------------------- 1) KV store
-- The ACTIVE backend. Every app record lives here as "<namespace>:<key>".
-- Namespaces: coach-os-saas       (accounts, sessions, workspaces, billing)
--             coach-os-workspaces (legacy pre-Phase-1.5 bytes)
--             shop-orders         (shop checkout orders + account index)
create table if not exists public.kv_store (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);
create index if not exists kv_store_updated_at_idx on public.kv_store (updated_at);

-- --------------------------------------------------------------- 2) Admin users
-- Dedicated table for admin-panel credentials. Mirrored automatically from
-- every KV account record with role='admin' (see section 7 below).
create table if not exists public.admin_users (
  id            text primary key,
  email         text unique not null,
  name          text not null default '',
  pass_salt     text not null default '',
  pass_hash     text not null default '',
  role          text not null default 'admin',
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  last_login_at timestamptz null
);

-- --------------------------------------- 3) Normalized SaaS tables (Phase-2 ready)
-- The app currently reads/writes kv_store; these tables are a queryable
-- relational mirror kept in sync by section 7, so reporting, backups and any
-- future phase can go row by row without another deploy.
create table if not exists public.coaches (
  id              text primary key,
  email           text unique not null,
  name            text not null default '',
  pass_salt       text not null default '',
  pass_hash       text not null default '',
  plan            text not null default 'trial',
  workspace_id    text null,
  trial_ends_at   timestamptz null,
  sub_status      text not null default 'trial',
  sub_ends_at     timestamptz null,
  sub_started_at  timestamptz null,
  created_at      timestamptz not null default now()
);
create index if not exists coaches_email_idx on public.coaches (lower(email));

create table if not exists public.sessions (
  token      text primary key,
  coach_id   text not null references public.coaches (id) on delete cascade,
  email      text not null default '',
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index if not exists sessions_coach_idx on public.sessions (coach_id);
create index if not exists sessions_expires_idx on public.sessions (expires_at);

create table if not exists public.workspaces (
  id             text primary key,
  code           text unique not null,
  owner_coach_id text null references public.coaches (id) on delete set null,
  plan           text not null default 'trial',
  status         text not null default 'trial',
  created_at     timestamptz not null default now(),
  claimed_at     timestamptz null
);
create index if not exists workspaces_code_idx on public.workspaces (code);
create index if not exists workspaces_owner_idx on public.workspaces (owner_coach_id);

create table if not exists public.workspace_data (
  workspace_id text primary key references public.workspaces (id) on delete cascade,
  rev          bigint not null default 0,
  data         jsonb not null default '{}'::jsonb,
  updated_at   timestamptz not null default now()
);

-- ------------------------------------------------- 4) Billing tables (Phase 2)
create table if not exists public.plans (
  id             text primary key,
  name           text not null,
  max_clients    int not null default 5,
  max_storage_mb int not null default 100,
  price_monthly  numeric not null default 0,
  price_currency text not null default 'IRT',
  is_active      boolean not null default true
);

create table if not exists public.coupons (
  code          text primary key,
  plan_id       text not null references public.plans (id),
  duration_days int not null default 30,
  max_uses      int not null default 1,
  used_count    int not null default 0,
  is_active     boolean not null default true,
  expires_at    timestamptz null,
  created_at    timestamptz not null default now()
);

create table if not exists public.payments (
  id            text primary key,
  coach_id      text not null references public.coaches (id) on delete cascade,
  plan_id       text not null default 'trial',
  amount        numeric not null default 0,
  currency      text not null default 'IRT',
  provider      text not null default 'manual',
  tracking_code text not null default '',
  status        text not null default 'pending',
  coupon_code   text null,
  starts_at     timestamptz null,
  ends_at       timestamptz null,
  created_at    timestamptz not null default now()
);
create index if not exists payments_coach_idx on public.payments (coach_id);
create index if not exists payments_status_idx on public.payments (status);

-- ------------------------------------------------------------- 5) Helper + view
-- KV timestamps are epoch milliseconds (jsonb numbers); convert safely.
-- Non-numeric / missing input -> NULL.
-- NOTE: STABLE, not IMMUTABLE. to_timestamp(double precision) is STABLE
-- because its result depends on the session TimeZone. Labelling this wrapper
-- IMMUTABLE is a lie Postgres accepts silently, and it would silently produce
-- stale/incorrect values if it were ever used in an index expression, a
-- generated column or a partition bound.
create or replace function public.ms_to_ts(ms text) returns timestamptz
language sql stable as $$
  select case when ms ~ '^\d+(\.\d+)?$'
              then to_timestamp(ms::double precision / 1000.0) end
$$;

create or replace view public.v_coach_overview as
select c.id, c.email, c.name, c.plan, c.sub_status, c.sub_ends_at, c.created_at,
       w.code as workspace_code, w.status as workspace_status,
       d.rev as data_rev, d.updated_at as data_updated_at
from public.coaches c
left join public.workspaces w on w.id = c.workspace_id
left join public.workspace_data d on d.workspace_id = w.id;

-- ------------------------------------------------------- 6) Static seed: plans
-- Mirrors PLANS in netlify/lib/billing.mjs (server-authoritative).
insert into public.plans (id, name, max_clients, max_storage_mb, price_monthly, price_currency, is_active) values
  ('trial',        'Trial',        5,   100,   0,       'IRT', true),
  ('basic',        'Basic',        5,   100,   290000,  'IRT', true),
  ('professional', 'Professional', 30,  2048,  790000,  'IRT', true),
  ('club',         'Club',         200, 10240, 2490000, 'IRT', true)
on conflict (id) do update set
  name = excluded.name,
  max_clients = excluded.max_clients,
  max_storage_mb = excluded.max_storage_mb,
  price_monthly = excluded.price_monthly,
  price_currency = excluded.price_currency,
  is_active = excluded.is_active;

