// CoachMint — generates backend/lib/fa-print.mjs from index.html.
//
// /api/export/pdf renders the printable plan page SERVER-SIDE, so it needs the
// Persian strings the app normally translates in the browser: the 154 exercise
// names (workout rows store an INDEX into the client's EXERCISES array — the
// backend must know the names to resolve them), the food names (FA_FOOD map)
// and the print-page UI strings. This script extracts all three from the app's
// FA dictionary so the two never drift, and writes a static module.
//
//   node scripts/gen-fa-print.mjs
//
// Re-run after adding exercises or changing FA translations in index.html.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(ROOT, 'index.html'), 'utf8');

/* Extract a balanced {…} object literal that starts at `start` (index of '{'). */
function balancedObject(src, start) {
  let depth = 0, i = start, q = null;
  while (i < src.length) {
    const c = src[i];
    if (q) {
      if (c === '\\') { i += 2; continue; }
      if (c === q) q = null;
    } else {
      if (c === '\'' || c === '"' || c === '`') q = c;
      else if (c === '{') depth++;
      else if (c === '}') { depth--; if (depth === 0) return src.slice(start, i + 1); }
    }
    i++;
  }
  throw new Error('unbalanced object literal');
}
const evalObj = (lit) => new Function(`return (${lit})`)();

/* 1) The app FA dictionary — everything translates through it. */
const faStart = html.indexOf('const FA={');
if (faStart < 0) throw new Error('FA dict not found');
const FA = evalObj(balancedObject(html, html.indexOf('{', faStart)));

/* 2) Exercise names IN ORDER (workout rows reference them by index). */
const exSlice = html.slice(html.indexOf('const EXERCISES=['), html.indexOf('const MUSCLES'));
const EX_EN = [];
const re = /\{n:(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"),m:/g;
let m;
while ((m = re.exec(exSlice))) EX_EN.push(m[1] !== undefined ? m[1].replace(/\\'/g, "'") : m[2]);

/* 3) Persian food names. */
const foodStart = html.indexOf('const FA_FOOD={');
const FA_FOOD = foodStart >= 0 ? evalObj(balancedObject(html, html.indexOf('{', foodStart))) : {};

/* 4) UI strings used by the export page (missing keys fall back to English). */
const UI_KEYS = [
  'Week Plan', 'Nutrition Plan', 'Exercise', 'Sets × Reps', 'Load', 'Rest', 'Notes',
  'Training Day', 'Rest Day', 'Meal', 'Foods', 'Calories', 'Scan to connect',
  'Open the CoachMint app — your plan syncs live', 'Coach', 'Goal', 'Program', 'Week',
  'sets', 'exercises', 'day streak', 'Points', 'Duration', 'Client',
  'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday',
  'Breakfast', 'Lunch', 'Dinner', 'Snack', 'Pre-Workout', 'Post-Workout',
  'Muscle Gain', 'Fat Loss', 'Strength', 'Endurance', 'Mobility', 'General Fitness',
  'Active', 'On Hold', 'Inactive', 'Pending', 'Archived',
  'Print / Save as PDF', 'Printed from CoachMint on', 'Connect with the QR code or the code below'
];

const out = { ...FA_FOOD };
UI_KEYS.forEach(k => { if (FA[k] !== undefined) out[k] = FA[k]; });
let exFa = 0;
EX_EN.forEach(n => { if (FA[n] !== undefined) { out[n] = FA[n]; exFa++; } });

const body =
`// AUTO-GENERATED by scripts/gen-fa-print.mjs — do not edit by hand.
// Source of truth: the FA dictionary + EXERCISES array in index.html.
// Re-generate after adding exercises or changing Persian translations:
//   node scripts/gen-fa-print.mjs

/* Exercise names in EXERCISES index order — workout rows store \`ex\` as an
   index into this array (custom exercises are appended AFTER it by the client
   and travel in the workspace payload as CEXS). */
export const EX_EN = ${JSON.stringify(EX_EN, null, 1)};

/* Persian translations: exercise names, food names and print-page UI strings.
   Lookup falls back to the English key when missing. */
export const FA_PRINT = ${JSON.stringify(out, null, 1)};
`;

writeFileSync(join(ROOT, 'backend', 'lib', 'fa-print.mjs'), body, 'utf8');
console.log(`fa-print.mjs written — ${EX_EN.length} exercises (${exFa} translated), ${Object.keys(out).length} total strings`);
