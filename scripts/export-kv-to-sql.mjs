// Coach OS — dump a KV JSON file into PostgreSQL INSERT statements and splice
// them into db/schema.sql (between the KV-DATA markers).
//
// The KV file is one JSON object: { "<namespace>:<key>": value, ... } — the
// exact layout the file backend (KV_FILE) uses. Every entry becomes one row of
// public.kv_store, so the dump is lossless for accounts (incl. the admin),
// sessions, workspaces, coupons, payments, shop orders and workspace payloads.
//
// Usage:
//   node ./scripts/export-kv-to-sql.mjs [input.json] [schema.sql|-]
// Defaults: data/kv-prod.json -> db/schema.sql
//   npm run db:dump                          # prod data into db/schema.sql
//   node ./scripts/export-kv-to-sql.mjs data/kv.json -   # dev data to stdout
import { readFileSync, writeFileSync, renameSync } from 'node:fs';

const [, , inputArg = 'data/kv-prod.json', outputArg = 'db/schema.sql'] = process.argv;

const BEGIN = '-- >>> KV-DATA-BEGIN (generated by scripts/export-kv-to-sql.mjs — do not edit by hand)';
const END = '-- <<< KV-DATA-END';

let data;
try {
  data = JSON.parse(readFileSync(inputArg, 'utf8'));
} catch (e) {
  console.error(`Cannot read KV file ${inputArg}: ${e.message}`);
  process.exit(1);
}
if (!data || typeof data !== 'object' || Array.isArray(data)) {
  console.error(`${inputArg} is not a KV JSON object ({ "<ns>:<key>": value, ... }).`);
  process.exit(1);
}

// SQL string literal: double any single quotes (standard_conforming_strings=on
// keeps backslashes literal, so no other escaping is needed).
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const keys = Object.keys(data).sort();
const lines = [];
for (const key of keys) {
  const val = data[key];
  if (val === undefined) continue;
  lines.push(
    `insert into public.kv_store (key, value) values (${q(key)}, ${q(JSON.stringify(val))}::jsonb)\n` +
    `on conflict (key) do update set value = excluded.value, updated_at = now();`
  );
}

const section = [
  BEGIN,
  `-- Source: ${inputArg} — ${keys.length} keys, dumped ${new Date().toISOString()}`,
  ...lines,
  END
].join('\n');

if (outputArg === '-') {
  console.log(section);
} else {
  let doc;
  try {
    doc = readFileSync(outputArg, 'utf8');
  } catch (e) {
    console.error(`Cannot read schema file ${outputArg}: ${e.message}`);
    process.exit(1);
  }
  const b = doc.indexOf(BEGIN);
  const e = doc.indexOf(END);
  if (b === -1 || e === -1 || e < b) {
    console.error(`KV-DATA markers not found in ${outputArg} — cannot splice.`);
    process.exit(1);
  }
  doc = doc.slice(0, b) + section + doc.slice(e + END.length);
  // Atomic write (temp file + rename): a crash or Ctrl-C mid-write used to
  // truncate db/schema.sql, destroying the DDL that only exists in that file.
  const tmp = `${outputArg}.${process.pid}.tmp`;
  writeFileSync(tmp, doc);
  renameSync(tmp, outputArg);
  console.log(`kv->sql: ${keys.length} keys from ${inputArg} written into ${outputArg}`);
}
